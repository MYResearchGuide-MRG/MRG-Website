-- Keep team display data in sync with committee assignments. Deletion is recoverable.
begin;

alter table public.myssp_projects add column deleted_at timestamptz;
alter table public.myssp_participants add column deleted_at timestamptz;
alter table public.myssp_participants add column display_profile jsonb not null default '{}';
alter table public.myssp_participants add column roster_order bigint generated by default as identity (start with 1000);

-- Match the original display roster before replacing positional profile IDs.
-- Retain edited names, schools, biographies and photos, without copying account emails.
do $$
declare person record; original jsonb; position bigint; saved jsonb;
begin
  for person in select p.*, b.payload, s.content from public.myssp_participants p
    join public.myssp_projects b on b.id=p.project_id
    left join public.myssp_submissions s on s.project_id=p.project_id loop
    select value, ordinality into original, position
    from jsonb_array_elements(coalesce(person.payload->'team','[]')) with ordinality
    where lower(trim(value->>'name'))=lower(trim(person.name)) limit 1;
    select value into saved from jsonb_array_elements(coalesce(person.content->'teamMembers','[]'))
    where value->>'id'=coalesce(original->>'memberId',person.project_id||':member-'||position)
      or lower(trim(value->>'name'))=lower(trim(person.name)) limit 1;
    update public.myssp_participants set
      roster_order=coalesce(position,roster_order),
      display_profile=jsonb_build_object('name',coalesce(saved->>'name',person.name),
        'school',coalesce(saved->>'school',original->>'school',''),
        'bio',coalesce(saved->>'bio',''),'photo',coalesce(saved->>'photo',''))
    where id=person.id;
  end loop;
end $$;

create function public.myssp_sync_team(project text) returns void
language plpgsql security definer set search_path='' as $$
declare members jsonb; team jsonb; project_code text;
begin
  select code into project_code from public.myssp_projects where id=project for update;
  if not found then return; end if;
  select coalesce(jsonb_agg(jsonb_build_object(
    'id',id::text,'name',coalesce(nullif(display_profile->>'name',''),name),
    'school',coalesce(display_profile->>'school',''),'bio',coalesce(display_profile->>'bio',''),
    'photo',coalesce(display_profile->>'photo','')) order by roster_order,id),'[]')
  into members from public.myssp_participants where project_id=project and deleted_at is null;
  select coalesce(jsonb_agg(jsonb_build_object('memberId',value->>'id','code',project_code,
    'name',value->>'name','school',value->>'school','bio',value->>'bio','photo',value->>'photo','programme','')),'[]') into team
  from jsonb_array_elements(members);
  update public.myssp_projects set payload=jsonb_set(payload,'{team}',team) where id=project;
  update public.myssp_submissions set content=jsonb_set(content,'{teamMembers}',members),
    revision=revision+1,updated_at=now()
  where project_id=project and content->'teamMembers' is distinct from members;
end $$;
revoke all on function public.myssp_sync_team(text) from public;

create function public.myssp_roster_changed() returns trigger
language plpgsql security definer set search_path='' as $$
begin
  if tg_op <> 'INSERT' then perform public.myssp_sync_team(old.project_id); end if;
  if tg_op <> 'DELETE' and (tg_op='INSERT' or new.project_id is distinct from old.project_id) then
    perform public.myssp_sync_team(new.project_id);
  end if;
  return null;
end $$;
revoke all on function public.myssp_roster_changed() from public;
create trigger myssp_roster_changed after insert or delete or update of project_id,name,deleted_at
on public.myssp_participants for each row execute function public.myssp_roster_changed();

do $$ declare project record; begin
  for project in select id from public.myssp_projects loop perform public.myssp_sync_team(project.id); end loop;
end $$;

-- A team may edit display profiles, but cannot add/remove people or change membership IDs.
create function public.myssp_capture_team_profiles() returns trigger
language plpgsql security definer set search_path='' as $$
declare member jsonb; expected jsonb; actual jsonb; team jsonb; project_code text;
begin
  if jsonb_typeof(new.content->'teamMembers') is distinct from 'array' then raise exception 'Team profiles required'; end if;
  select coalesce(jsonb_agg(id::text order by roster_order,id),'[]') into expected
  from public.myssp_participants where project_id=new.project_id and deleted_at is null;
  select coalesce(jsonb_agg(value->>'id'),'[]') into actual from jsonb_array_elements(new.content->'teamMembers');
  if actual <> expected then raise exception 'The committee changed this team. Reload before saving.'; end if;
  for member in select value from jsonb_array_elements(new.content->'teamMembers') loop
    if exists(select 1 from unnest(array['id','name','school','bio','photo']) as field
      where jsonb_typeof(member->field) is distinct from 'string')
      or length(trim(member->>'name')) not between 1 and 100
      or length(member->>'school') > 200 or length(member->>'bio') > 500
      or length(member->>'photo') > 350000
      or (member->>'photo' <> '' and member->>'photo' !~ '^data:image/jpeg;base64,[A-Za-z0-9+/]+=*$')
      or (member - array['id','name','school','bio','photo']) <> '{}'::jsonb then
      raise exception 'Invalid team profile';
    end if;
    update public.myssp_participants set display_profile=member-'id'
      where id=(member->>'id')::uuid and project_id=new.project_id and deleted_at is null;
  end loop;
  select code into project_code from public.myssp_projects where id=new.project_id;
  select coalesce(jsonb_agg(jsonb_build_object('memberId',value->>'id','code',project_code,
    'name',value->>'name','school',value->>'school','bio',value->>'bio','photo',value->>'photo','programme','')),'[]') into team
    from jsonb_array_elements(new.content->'teamMembers');
  update public.myssp_projects set payload=jsonb_set(payload,'{team}',team) where id=new.project_id;
  return new;
end $$;
revoke all on function public.myssp_capture_team_profiles() from public;
create trigger myssp_capture_team_profiles before insert or update of content on public.myssp_submissions
for each row execute function public.myssp_capture_team_profiles();

create or replace function public.myssp_is_member(project text) returns boolean
language sql stable security definer set search_path='' as $$
  select exists(select 1 from public.myssp_participants p join public.myssp_projects b on b.id=p.project_id
    where p.user_id=(select auth.uid()) and p.project_id=project and not p.revoked
      and p.deleted_at is null and b.deleted_at is null and not b.retired);
$$;
alter policy projects_read on public.myssp_projects using (
  public.myssp_is_admin() or (deleted_at is null and not retired and (published or public.myssp_is_member(id))));
alter policy participants_read on public.myssp_participants using (
  public.myssp_is_admin() or (user_id=(select auth.uid()) and deleted_at is null and not revoked
    and public.myssp_is_member(project_id)));
alter policy participants_admin_update on public.myssp_participants with check (
  public.myssp_is_admin() and exists(select 1 from public.myssp_projects p
    where p.id=project_id and not p.retired and p.deleted_at is null));
alter policy submissions_read on public.myssp_submissions using (
  exists(select 1 from public.myssp_projects p where p.id=project_id and
    (public.myssp_is_admin() or (p.deleted_at is null and not p.retired and (p.published or public.myssp_is_member(p.id))))));

create function public.myssp_set_deleted(kind text, record_id text, remove boolean, destination text default null)
returns void language plpgsql security definer set search_path='' as $$
declare target text;
begin
  if not public.myssp_is_admin() then raise exception 'Admin required' using errcode='42501'; end if;
  if remove is null then raise exception 'Choose delete or restore'; end if;
  if kind='participant' then
    select project_id into target from public.myssp_participants where id=record_id::uuid for update;
    if not found then raise exception 'Participant not found'; end if;
    if not remove then
      target := coalesce(destination,target);
      if not exists(select 1 from public.myssp_projects where id=target and not retired and deleted_at is null) then
        raise exception 'Choose an active project before restoring this participant';
      end if;
    end if;
    update public.myssp_participants set deleted_at=case when remove then now() else null end,
      project_id=target where id=record_id::uuid;
  elsif kind='project' then
    perform 1 from public.myssp_projects where id=record_id and not retired for update;
    if not found then raise exception 'Project not found'; end if;
    -- Restoring never silently republishes a project or unlocks editing.
    update public.myssp_projects set deleted_at=case when remove then now() else null end,
      published=false,editing_enabled=false where id=record_id;
  else raise exception 'Unknown record type'; end if;
end $$;
revoke all on function public.myssp_set_deleted(text,text,boolean,text) from public;
grant execute on function public.myssp_set_deleted(text,text,boolean,text) to authenticated;

create or replace function public.myssp_import_participants(rows jsonb) returns integer
language plpgsql security definer set search_path='' as $$
declare r jsonb; total integer := 0;
begin
  if not public.myssp_is_admin() then raise exception 'Admin required' using errcode='42501'; end if;
  if jsonb_typeof(rows) <> 'array' or jsonb_array_length(rows) not between 1 and 200 then raise exception 'Import 1 to 200 rows'; end if;
  for r in select value from jsonb_array_elements(rows) loop
    if not exists(select 1 from public.myssp_projects where id=r->>'project_id' and not retired and deleted_at is null) then raise exception 'Unknown project'; end if;
    insert into public.myssp_participants(name,email,project_id) values(trim(r->>'name'),lower(trim(r->>'email')),r->>'project_id');
    total := total+1;
  end loop;
  return total;
end $$;

create or replace function public.myssp_split_project(parent text, children jsonb, assignments jsonb) returns void
language plpgsql security definer set search_path='' as $$
declare r jsonb; old_project public.myssp_projects; member public.myssp_participants; child_ids text[];
begin
  if not public.myssp_is_admin() then raise exception 'Admin required' using errcode='42501'; end if;
  select * into old_project from public.myssp_projects where id=parent and not retired and deleted_at is null for update;
  if not found then raise exception 'Project unavailable'; end if;
  if jsonb_typeof(children) <> 'array' or jsonb_array_length(children) not between 2 and 6 or jsonb_typeof(assignments) <> 'object' then raise exception 'Invalid split'; end if;
  select array_agg(value->>'id') into child_ids from jsonb_array_elements(children);
  for member in select * from public.myssp_participants where project_id=parent and deleted_at is null for update loop
    if not coalesce((assignments->>member.id::text)=any(child_ids),false) then raise exception 'Assign every participant'; end if;
  end loop;
  for r in select value from jsonb_array_elements(children) loop
    if r->>'code' not like old_project.code||'%' or length(trim(r->'payload'->>'title')) not between 1 and 240 then raise exception 'Invalid child project'; end if;
    insert into public.myssp_projects(id,code,payload,parent_id)
      values(r->>'id',r->>'code',jsonb_set(r->'payload','{team}','[]'),parent);
  end loop;
  update public.myssp_participants set project_id=assignments->>id::text where project_id=parent and deleted_at is null;
  update public.myssp_projects set retired=true,published=false,editing_enabled=false where id=parent;
end $$;

create or replace function public.myssp_claim_invitation(person uuid) returns boolean
language plpgsql security definer set search_path='' as $$
begin
  update public.myssp_participants set invite_requested_at=now()
  where id=person and not revoked and deleted_at is null
    and exists(select 1 from public.myssp_projects p where p.id=project_id and not p.retired and p.deleted_at is null)
    and (invite_requested_at is null or invite_requested_at < now()-interval '60 seconds');
  return found;
end $$;

